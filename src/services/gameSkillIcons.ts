export function skillArtworkId(characterClass: string, name: string): string | undefined {
  const classKey = characterClass.toLowerCase();
  const skillKey = name.toLowerCase().replace(/[^a-z0-9]/g, '');
  return skillIcons[classKey]?.[skillKey] ? `skill.${classKey}.${skillKey}` : undefined;
}
export const skillBindings = Object.fromEntries(
  Object.entries(skillIcons).flatMap(([characterClass, icons]) =>
    Object.entries(icons).map(([name, key]) => [`skill.${characterClass}.${name}`, key]),
  ),
);
